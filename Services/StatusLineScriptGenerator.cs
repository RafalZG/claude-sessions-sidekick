namespace ClaudeSessionsSidekick.Services;

/// <summary>
/// Turns a status line template into a standalone PowerShell script that
/// Claude Code runs for every status line refresh. Windows PowerShell 5.1
/// compatible on purpose (no <c>??</c>, no ternary) — Claude Code falls back
/// to stock powershell.exe when Git Bash isn't installed, and powershell.exe
/// is what the generated settings.json entry invokes explicitly.
/// </summary>
public static class StatusLineScriptGenerator
{
    /// <summary>
    /// The template is baked into the script as a single-quoted PowerShell
    /// string. PowerShell's tokenizer accepts not just the ASCII apostrophe
    /// but the whole "smart quote" family (U+2018–U+201B) as that string's
    /// delimiter, so every one of them must be doubled — doubling only
    /// <c>'</c> leaves a way out of the string. Escape sequences on purpose:
    /// the characters themselves are invisible in a diff and an ANSI re-save
    /// of this file would silently change what gets matched.
    /// </summary>
    internal static string EscapeForSingleQuotedPs(string text)
    {
        var escaped = text
            .Replace("'", "''")
            .Replace("\u2018", "\u2018\u2018")
            .Replace("\u2019", "\u2019\u2019")
            .Replace("\u201A", "\u201A\u201A")
            .Replace("\u201B", "\u201B\u201B");
        return escaped;
    }

    /// <summary>
    /// Control characters have no business in a one-line status template, and
    /// the C1 range (U+007F–U+009F) is actively dangerous: if the script file
    /// were ever read in an ANSI codepage, a C1 byte can decode into a smart
    /// quote and terminate the baked string. Strip them all before escaping.
    /// </summary>
    internal static string StripControlCharacters(string text)
    {
        var kept = text.Where(c => c >= ' ' && !(c >= (char)0x7F && c <= (char)0x9F)).ToArray();
        var cleaned = new string(kept);
        return cleaned;
    }

    private static string BlockAnsi(string token)
    {
        return StatusLineTemplate.BlockColors[token].Ansi;
    }

    public static string Generate(string template)
    {
        ArgumentNullException.ThrowIfNull(template);
        if (template.Length > StatusLineTemplate.MaxTemplateLength)
        {
            throw new ArgumentException(
                $"Template longer than {StatusLineTemplate.MaxTemplateLength} characters.", nameof(template));
        }

        // A status line is one line — turn line breaks and tabs from a paste
        // into spaces (the control-char strip below would glue words together).
        var flat = template
            .Replace("\r\n", " ")
            .Replace('\r', ' ')
            .Replace('\n', ' ')
            .Replace('\t', ' ');
        var safe = StripControlCharacters(flat);
        var baked = EscapeForSingleQuotedPs(safe);

        return $$"""
            # Generated by Claude Sessions Sidekick — edit in the app (tray > Tools > Status Line), not here.
            $ErrorActionPreference = 'SilentlyContinue'
            # UTF-8 output so non-ASCII template text survives; the setter can
            # throw when the process has no console, hence the try.
            try { [Console]::OutputEncoding = [Text.Encoding]::UTF8 } catch { }
            $raw = [Console]::In.ReadToEnd()
            $data = $null
            try { $data = ConvertFrom-Json $raw } catch { }
            if (-not $data) {
                # No usable input — print nothing rather than a template skeleton.
                exit 0
            }

            function Get-GitBranch([string]$startDir) {
                $dir = $startDir
                while ($dir) {
                    $gitPath = Join-Path $dir '.git'
                    if (Test-Path -LiteralPath $gitPath) {
                        $gitDir = $gitPath
                        if (Test-Path -LiteralPath $gitPath -PathType Leaf) {
                            # Worktree: .git is a one-line file "gitdir: <real dir>"
                            $firstLine = [string](Get-Content -LiteralPath $gitPath -TotalCount 1)
                            if ($firstLine -match '^gitdir:\s*(.+)$') {
                                $gitDir = $Matches[1].Trim()
                                if (-not [IO.Path]::IsPathRooted($gitDir)) { $gitDir = Join-Path $dir $gitDir }
                            }
                        }
                        $headPath = Join-Path $gitDir 'HEAD'
                        if (Test-Path -LiteralPath $headPath) {
                            $head = [string](Get-Content -LiteralPath $headPath -TotalCount 1)
                            if ($head -match '^ref: refs/heads/(.+)$') { return $Matches[1] }
                            if ($head.Length -ge 7) { return $head.Substring(0, 7) }
                        }
                        return ''
                    }
                    $parent = Split-Path -Parent $dir
                    if ($parent -eq $dir) { return '' }
                    $dir = $parent
                }
                return ''
            }

            $project = ''; $branch = ''; $worktree = ''; $model = ''; $ctx = ''
            $cost = ''; $lines = ''; $version = ''; $effort = ''; $h5 = ''; $d7 = ''
            $dir = [string]$data.workspace.project_dir
            if (-not $dir) { $dir = [string]$data.cwd }
            if ($dir) { $project = Split-Path -Leaf $dir }
            $cwd = [string]$data.cwd
            if (-not $cwd) { $cwd = $dir }
            if ($cwd) { $branch = Get-GitBranch $cwd }
            # Linked worktrees report their name two ways depending on how the
            # session was started; empty everywhere else.
            $worktree = [string]$data.workspace.git_worktree
            if (-not $worktree) { $worktree = [string]$data.worktree.name }
            $model = [string]$data.model.display_name
            if ($null -ne $data.context_window.used_percentage) {
                $ctx = [string][math]::Round([double]$data.context_window.used_percentage)
            }
            if ($null -ne $data.cost.total_cost_usd) {
                $cost = [string]::Format([Globalization.CultureInfo]::InvariantCulture, '${0:0.00}', [double]$data.cost.total_cost_usd)
            }
            if ($null -ne $data.cost.total_lines_added) {
                $lines = '+' + [string]$data.cost.total_lines_added + '/-' + [string]$data.cost.total_lines_removed
            }
            $version = [string]$data.version
            $effort = [string]$data.effort.level
            if ($null -ne $data.rate_limits.five_hour.used_percentage) {
                $h5 = [string][math]::Round([double]$data.rate_limits.five_hour.used_percentage)
            }
            if ($null -ne $data.rate_limits.seven_day.used_percentage) {
                $d7 = [string][math]::Round([double]$data.rate_limits.seven_day.used_percentage)
            }

            # Free-text values come from outside (stdin JSON, .git/HEAD read as
            # a plain file) — strip control characters BEFORE coloring, so a
            # crafted value can't smuggle ESC into the terminal and the strip
            # can't eat the ESC the coloring is about to add. Numeric values
            # are safe by construction.
            $project = $project -replace '[\x00-\x1F\x7F]', ''
            $branch = $branch -replace '[\x00-\x1F\x7F]', ''
            $worktree = $worktree -replace '[\x00-\x1F\x7F]', ''
            $model = $model -replace '[\x00-\x1F\x7F]', ''
            $version = $version -replace '[\x00-\x1F\x7F]', ''
            $effort = $effort -replace '[\x00-\x1F\x7F]', ''

            # Colors: values get ANSI colors, surrounding template text stays
            # default. Empty values stay empty so the ()/[] tidy-up still works.
            $esc = [char]27
            function Add-Color([string]$value, [string]$code) {
                if ($value -and $code) { return "$esc[" + $code + 'm' + $value + "$esc[0m" }
                return $value
            }
            function Get-PctColor([string]$value) {
                $n = 0
                if ($value -and [int]::TryParse($value, [ref]$n)) {
                    if ($n -ge {{StatusLineTemplate.PercentCritThreshold}}) { return '{{StatusLineTemplate.PercentColor(100).Ansi}}' }
                    if ($n -ge {{StatusLineTemplate.PercentWarnThreshold}}) { return '{{StatusLineTemplate.PercentColor(60).Ansi}}' }
                    return '{{StatusLineTemplate.PercentColor(0).Ansi}}'
                }
                return ''
            }
            $project = Add-Color $project '{{BlockAnsi("{project}")}}'
            $worktree = Add-Color $worktree '{{BlockAnsi("{worktree}")}}'
            $branch = Add-Color $branch '{{BlockAnsi("{branch}")}}'
            $model = Add-Color $model '{{BlockAnsi("{model}")}}'
            $version = Add-Color $version '{{BlockAnsi("{version}")}}'
            $effort = Add-Color $effort '{{BlockAnsi("{effort}")}}'
            $ctx = Add-Color $ctx (Get-PctColor $ctx)
            $h5 = Add-Color $h5 (Get-PctColor $h5)
            $d7 = Add-Color $d7 (Get-PctColor $d7)

            $line = '{{baked}}'
            $line = $line.Replace('{project}', $project).Replace('{branch}', $branch)
            $line = $line.Replace('{worktree}', $worktree)
            $line = $line.Replace('{model}', $model).Replace('{ctx}', $ctx)
            $line = $line.Replace('{cost}', $cost).Replace('{lines}', $lines)
            $line = $line.Replace('{version}', $version).Replace('{effort}', $effort)
            $line = $line.Replace('{5h}', $h5).Replace('{7d}', $d7)
            $line = $line -replace '\(\s*\)|\[\s*\]', ''
            $line = ($line -replace '\s{2,}', ' ').Trim()
            [Console]::Out.Write($line)
            exit 0
            """;
    }
}
